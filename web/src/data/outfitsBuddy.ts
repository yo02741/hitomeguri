/**
 * 夥伴的第二批（使用者回饋：夥伴多生一些）。不限縣，全部用抽獎券抽；24 隻：常見 8、少見 11、稀有 5。
 * 題材是旅途上遇得到的動物、日本生活裡的小東西與季節的擺設（雪兔、鏡餅、月見糰子、蚊香豬、暖桌）。
 * 畫法同 outfits.ts 的招財貓、柴犬：站在旅人左腳邊（約 x 14–104、y 196–300），腳落在 y 292–298 的地面；
 * 剪紙、平塗、不描黑邊，只用同色的淡邊（E）與一層陰影（SH）。
 * 3D 是把這張圖充氣成一塊：細線（腳、鬚、煙）至少 2.4 寬，單獨露在外面的部分不透明度不低於 0.7。
 */

const shade = (d: string) => `<path d="${d}" ${SH}/>`
const circ = (cx: number, cy: number, r: number, fill: string, extra = '') => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}" ${E} ${extra}/>`
const ell = (cx: number, cy: number, rx: number, ry: number, fill: string, extra = '') =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" ${E} ${extra}/>`
/** 眼睛：墨點，上面一點白的反光 */
const eyes = (pts: Array<[number, number]>, r = 2.4) => dots(C.ink, r, pts) + dots(C.white, r * 0.36, pts.map(([x, y]) => [x + r * 0.35, y - r * 0.35]))
/** 腮紅 */
const blush = (pts: Array<[number, number]>, rx = 3, ry = 1.8) =>
  `<g fill="${C.pink}" opacity=".8">${pts.map(([x, y]) => `<ellipse cx="${x}" cy="${y}" rx="${rx}" ry="${ry}"/>`).join('')}</g>`
/** 鋸齒的半圓（刺蝟的刺）：從角度 a0 到 a1（度，0 在右、往上為正），尖 r1、凹 r2 */
function spikes(cx: number, cy: number, r1: number, r2: number, a0: number, a1: number, n: number): string {
  const pts: string[] = []
  for (let i = 0; i <= n * 2; i++) {
    const a = ((a0 + ((a1 - a0) * i) / (n * 2)) * Math.PI) / 180
    const r = i % 2 ? r1 : r2
    pts.push(`${+(cx + r * Math.cos(a)).toFixed(1)} ${+(cy - r * Math.sin(a)).toFixed(1)}`)
  }
  return `M${pts.join(' L')}`
}
